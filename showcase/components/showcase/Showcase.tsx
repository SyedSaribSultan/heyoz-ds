export function Showcase({ staleSources = [] }: { staleSources?: string[] }) {
  const entries = registry.all;

  /* Components are links now, not anchors. Each is its own route — see
   * ComponentPage.tsx for why the single scroll stopped working once the written
   * guidance landed. The rail still lists every one of them, because the list is how
   * somebody finds the one they want, and losing it to save a click would be the wrong
   * trade.
   *
   * That sentence read "all nine" while the catalogue held fourteen. The list is
   * `entries`, so it should never have carried a numeral at all — see the note in
   * ComponentPage.tsx for how far that particular figure spread before anyone counted. */
  /* One rail group per component family, rather than one flat list of every component.
   *
   * It was one flat list, and the list was in REGISTRATION order — which is the order the
   * components were built in. So Icon Button and Button Link sat tenth and eleventh instead of
   * beside Button, and the form controls added in one batch appeared before the three they
   * exist to sit with. Chronology is information about this repository, not about the system,
   * and at fourteen items it was merely odd; at thirty-four it was the only thing wrong with
   * the rail that a reader would actually notice.
   *
   * `registry.byGroup` supplies both the grouping and the ordering, and the index reads the
   * same accessor — two orderings of one catalogue is the drift the registry exists to
   * prevent, and it would surface as a rail whose sequence disagreed with the page under it.
   *
   * The count on each label is doing real work: `Forms 11` tells a first-time reader the shape
   * of the system in a way that thirty-four names in a column cannot. */
  const navGroups: NavGroup[] = [
    { label: 'foundations', items: FOUNDATION_SECTIONS },
    ...registry.byGroup.map(({ group, entries: inGroup }) => ({
      label: `${group.label} · ${inGroup.length}`,
      items: inGroup.map((e) => ({
        id: e.recipe.id,
        label: e.recipe.meta.title,
        href: `/c/${e.recipe.id}`,
      })),
    })),
    { label: 'in context', items: [{ id: 'assembled', label: 'Assembled' }] },
  ];

  /* Section numbering is derived, so inserting a component renumbers everything
   * after it without anyone maintaining a list of numbers. */
  const pad = (n: number) => String(n).padStart(2, '0');
  let n = 0;

  return (
    <ThemeProvider>
      <a
        href="#main"
        className="sr-only focus:not-sr-only focus:absolute focus:left-space-4 focus:top-space-4 focus:z-tooltip focus:rounded-4 focus:bg-fill-inverse focus:px-space-4 focus:py-space-3 focus:text-label-sm focus:text-content-on-inverse"
      >
        Skip to content
      </a>

      <Header staleSources={staleSources} />

      <div className="mx-auto grid max-w-container-xl grid-cols-1 gap-x-space-9 px-space-6 lg:grid-cols-rail">
        <NavRail groups={navGroups} />

        <main id="main" className="min-w-0 pb-space-18">
          <Intro />

          <Primitives index={pad(++n)} />
          <Foundations index={pad(++n)} />
          <Typography index={pad(++n)} />
          <Elevation index={pad(++n)} />
          <Spectrum index={pad(++n)} />

          {/* One index tile per component, each linking to its own route. This used to
              be one full ComponentSection per component, inline — ~150,000px of page
              once the guidance landed. (It said "nine full ComponentSections"; the
              earliest commit that has this file already registered fourteen, so the
              count was describing a catalogue that predates the history.) */}
          <ComponentIndex index={pad(++n)} />

          <Assembled index={pad(++n)} />
          <Footer />
        </main>
      </div>
    </ThemeProvider>
  );
}
