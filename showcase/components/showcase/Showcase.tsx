/* ---------------------------------------------------------------------------
 * The page.
 *
 * Note what is not here: a list of components. The component sections and their nav
 * entries both come from `registry.all`, which is populated by catalog.tsx. Adding a
 * component is a recipe, a React component and one registration — this file does not
 * change.
 * ------------------------------------------------------------------------- */

/* Primitives first: the semantic section is built out of it, and reading the ramps
 * before the roles is the order that makes the roles make sense. */
const FOUNDATION_SECTIONS = [
  { id: 'primitives', label: 'Primitives' },
  { id: 'colour', label: 'Colour' },
  { id: 'typography', label: 'Typography' },
  { id: 'elevation', label: 'Elevation & motion' },
  { id: 'spectrum', label: 'Charts & gradients' },
];

/* The first screen of a page that ships publicly to people deciding whether to trust
 * this system, so it is allowed to be the loudest thing here — and it was not. The
 * headline sat at display-sm while display-md and display-lg went unused, which put
 * the whole page inside two steps of a fifteen-step scale.
 *
 * The five figures are the argument, so they are set at display-sm — the size the
 * headline used to be — rather than heading-md. Their labels keep the uppercase mono
 * treatment that was dropped elsewhere: it is right for a two-word eyebrow over a
 * numeral and wrong for a five-word section label, which is the distinction the old
 * page did not draw. */
function Intro() {
  return (
    <div className="pt-space-11">
      <h1 className="max-w-[22ch] font-display text-display-lg font-extrabold text-content-primary">
        Every specimen on this page is the component.
      </h1>
      <p className="mt-space-7 max-w-[58ch] text-body-lg text-content-secondary">
        Not a picture of it, not a copy of its CSS. Each component has one recipe class that
        owns its variants, states and token bindings; the component renders from it and so does
        every table, grid and snippet below. The documentation cannot drift from the code because
        it is not a description of the code.
      </p>
      <dl className="mt-space-12 grid grid-cols-2 gap-x-space-6 gap-y-space-9 border-t-2 border-border-primary pt-space-8 sm:grid-cols-3 lg:grid-cols-5">
        {[
          [`${registry.size}`, 'components', 'each one recipe class'],
          [`${primitiveSummary.total}`, 'primitives', `${primitiveSummary.families} families, one palette`],
          [`${registry.tokenCoverage.length}`, 'tokens named', 'across every recipe'],
          [`${auditSummary.passing}/${auditSummary.gates}`, 'gates passing', 'measured by the build'],
          ['0', 'hex values', 'anywhere above tier 1'],
        ].map(([value, label, sub]) => (
          <div key={label}>
            <dt className="font-mono text-label-sm uppercase text-content-tertiary">
              {label}
            </dt>
            {/* tabular-nums so 655 and 188/188 sit on the same grid as 0 and 9. */}
            <dd className="mt-space-3 font-display text-display-sm font-extrabold tabular-nums text-content-primary">
              {value}
            </dd>
            <dd className="mt-space-2 max-w-[22ch] text-body-sm text-content-tertiary">{sub}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

